import { GeneratedWorld } from '../../engine/worldgen/index.js';
import { getTenant } from '../../storage/tenant-context.js';
import { onRollback } from '../../storage/unit-of-work.js';

let nextManagerId = 0;

const DEFAULT_MAX_CACHED_WORLDS = 32;

function maxCachedWorlds(): number {
    const configured = Number.parseInt(process.env.RPG_MAX_CACHED_WORLDS ?? '', 10);
    return Number.isInteger(configured) && configured > 0 ? configured : DEFAULT_MAX_CACHED_WORLDS;
}

/**
 * In-memory cache of generated worlds.
 *
 * A cache only: every world is also stored as a snapshot in its campaign's
 * database, and readers restore from there on a miss. Two properties follow.
 *
 * - **Scoped to the campaign.** The process serves every campaign, and world
 *   ids (`world-<seed>-<timestamp>`) are guessable, so entries are keyed by
 *   the request's verified tenant as well as the id. One campaign cannot read,
 *   replace or delete another's world by naming its id.
 * - **Bounded.** A world can be a million tiles. The cache keeps the most
 *   recently used few and lets the rest be restored on demand, instead of
 *   holding every world ever generated for the life of the process.
 */
export class WorldManager {
    /** Most recently used last. */
    private worlds: Map<string, GeneratedWorld> = new Map();
    private readonly managerId = ++nextManagerId;

    private scope(): string {
        const tenant = getTenant();
        // JSON so no choice of ids can make two scopes collide.
        return tenant ? JSON.stringify([tenant.accountId, tenant.campaignId]) : '';
    }

    private key(id: string): string {
        return `${this.scope()}|${id}`;
    }

    create(id: string, world: GeneratedWorld): void {
        const key = this.key(id);
        if (this.worlds.has(key)) {
            throw new Error(`World ${id} already exists`);
        }
        // A world generated by a call that later rolls back must not outlive it.
        onRollback(() => { this.worlds.delete(key); }, `world:${this.managerId}:${key}`);
        this.worlds.set(key, world);

        const cap = maxCachedWorlds();
        while (this.worlds.size > cap) {
            const oldest = this.worlds.keys().next().value as string | undefined;
            if (oldest === undefined || oldest === key) break;
            this.worlds.delete(oldest);
        }
    }

    get(id: string): GeneratedWorld | null {
        const key = this.key(id);
        const world = this.worlds.get(key);
        if (!world) return null;
        // Re-insert to mark most recently used.
        this.worlds.delete(key);
        this.worlds.set(key, world);
        return world;
    }

    delete(id: string): boolean {
        return this.worlds.delete(this.key(id));
    }

    /** Ids of the cached worlds belonging to the current campaign. */
    list(): string[] {
        const prefix = `${this.scope()}|`;
        return Array.from(this.worlds.keys())
            .filter(key => key.startsWith(prefix))
            .map(key => key.slice(prefix.length));
    }
}

// Singleton for server lifetime
let instance: WorldManager | null = null;
export function getWorldManager(): WorldManager {
    if (!instance) instance = new WorldManager();
    return instance;
}
